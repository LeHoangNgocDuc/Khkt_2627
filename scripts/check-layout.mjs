import fs from 'node:fs';
const read=(file)=>fs.readFileSync(new URL('../'+file,import.meta.url),'utf8');
const app=read('src/App.tsx');
const identity=read('src/components/SchoolIdentity.tsx');
const work=read('src/Workbench.tsx');
const flat=read('src/components/FlatLayBoard.tsx');
const pitch=read('src/components/PitchBoardTV.tsx');
const layout=read('src/layout-v5.css');
const errors=[];
const requireCheck=(condition,why)=>{if(!condition)errors.push(why)};
requireCheck(app.includes('VISIONBOT – RÔ-BỐT AI HỖ TRỢ NGƯỜI KHIẾM THỊ'),'Thiếu tiêu đề dự án ở Header');
requireCheck(app.includes('<SchoolIdentity compact editable competition/>'),'Thiếu nhận diện trường trên Header');
requireCheck(identity.includes("../../Logo.jpg")&&identity.includes('/logo-truong.png'),'Thiếu đường dẫn logo từ GitHub / public');
requireCheck(app.includes('sidebarCollapsed')&&app.includes('toggleFullscreen'),'Chưa có thu gọn sidebar và toàn màn hình');
requireCheck(work.indexOf('<div className="scene-toolbar-docked">')>work.indexOf('<div className="canvas-stage">'),'Thanh công cụ 3D chưa được đưa ra ngoài canvas');
const sceneStart=work.indexOf('<div className="canvas-stage">');
const sceneEnd=work.indexOf('<div className="scene-toolbar-docked">');
const scene=work.slice(sceneStart,sceneEnd);
requireCheck(!scene.includes('stage-info-card')&&!scene.includes('quick-presets'),'3D còn thẻ nổi đè lên mô hình');
const flatStart=flat.indexOf('<div className="flat-board-stage">');
const flatEnd=flat.indexOf('<div className="flat-bottom-hints flat-bottom-docked">');
const board=flat.slice(flatStart,flatEnd);
requireCheck(!board.includes('flat-meter')&&!board.includes('flat-canvas-tools')&&!board.includes('flat-hover-tooltip'),'Bảng 2D còn hộp nổi che mạch');
requireCheck(flat.indexOf('flat-meter')>flat.indexOf('<aside className={`flat-inspector'),'Đồng hồ ảo không nằm trong bảng dock');
requireCheck(pitch.indexOf('tv-summary-panel')>pitch.indexOf('</div>\n      {wiringMode&&!notesOpen'),'BGK thiếu bảng giải thích dock');
requireCheck(layout.includes('grid-template-columns:minmax(0,1fr) 360px'),'Thiếu bố cục sidebar 360px');
requireCheck(layout.includes('.flat-collapsed-status')&&layout.includes('.workbench-inline-status'),'Thiếu dải trạng thái khi thu gọn');
console.log(`Kiểm tra bố cục VisionBot V5: ${errors.length?'FAILED':'PASS'}`);
if(errors.length){console.error(errors.join('\n'));process.exit(1);}
console.log('Header + logo GitHub + 3D dock + 2D dock + BGK dock + trạng thái thu gọn hợp lệ.');
