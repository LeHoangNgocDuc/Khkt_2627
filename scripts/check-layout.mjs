import fs from 'node:fs';
const read=(file)=>fs.readFileSync(new URL('../'+file,import.meta.url),'utf8');
const exists=(file)=>fs.existsSync(new URL('../'+file,import.meta.url));
const app=read('src/App.tsx');
const identity=read('src/data/identity.ts');
const school=read('src/components/SchoolIdentity.tsx');
const work=read('src/Workbench.tsx');
const flat=read('src/components/FlatLayBoard.tsx');
const layout=read('src/layout-v5.css');
const focus=read('src/refocus-v6.css');
const errors=[];
function check(ok,message){if(!ok)errors.push(message)}
check(identity.includes('Đôi mắt AI, đồng hành cùng học sinh khiếm thị trên hành trình học tập hòa nhập'),'Sai tên đề tài mới.');
check((app.match(/id:'(intro|model|wiring|principle)'/g)||[]).length===4,'Thanh điều hướng không đủ đúng 4 phân khu.');
check(!app.includes("section==='demo'")&&!app.includes("section==='results'")&&!app.includes("section==='presentation'"),'Chưa loại bỏ 3 phân khu cũ.');
check(app.includes('<SchoolIdentity compact editable competition/>'),'Header thiếu tên trường và logo.');
check(school.includes('Logo.jpg')&&school.includes('/logo-truong.png'),'Thiếu đường dẫn logo đã có trên GitHub.');
check(exists('public/images/visionbot-thuc-te-1.png')&&exists('public/images/visionbot-thuc-te-2.png'),'Thiếu ảnh sản phẩm gốc.');
check(read('src/components/IntroPage.tsx').includes('ẢNH CHỤP SẢN PHẨM THỰC TẾ'),'Chưa chuyển trang giới thiệu sang ảnh thật.');
check(exists('src/components/ModelPage.tsx')&&exists('src/components/PrinciplePage.tsx'),'Thiếu chế độ cấu tạo và nguyên lý mới.');
check(work.indexOf('<div className="scene-toolbar-docked">')>work.indexOf('<div className="canvas-stage">'),'3D chưa dock công cụ bên ngoài.');
const scene=work.slice(work.indexOf('<div className="canvas-stage">'),work.indexOf('<div className="scene-toolbar-docked">'));
check(!scene.includes('stage-info-card')&&!scene.includes('quick-presets'),'Thẻ nổi còn che mô hình 3D.');
const board=flat.slice(flat.indexOf('<div className="flat-board-stage">'),flat.indexOf('<div className="flat-bottom-hints flat-bottom-docked">'));
check(!board.includes('flat-meter')&&!board.includes('flat-hover-tooltip'),'Thẻ nổi còn che bảng đấu nối.');
check(flat.indexOf('flat-meter')>flat.indexOf('<aside className={`flat-inspector'),'Đồng hồ chưa nằm ở bảng thông số dock.');
check(layout.includes('grid-template-columns:minmax(0,1fr) 360px')&&focus.includes('model-v6-body'),'Thiếu layout cột độc lập 360px.');
check(focus.includes('.model-v6-inspector.open')&&focus.includes('.principle-v6-side.open'),'Thiếu bảng thông tin mobile.');
console.log(`Kiểm tra giao diện VisionBot V6: ${errors.length?'FAILED':'PASS'}`);
if(errors.length){console.error(errors.join('\n'));process.exit(1)}
console.log('4 phân khu + tên mới + ảnh thật + 3D + mạch dock + nguyên lý + responsive hợp lệ về cấu trúc.');
